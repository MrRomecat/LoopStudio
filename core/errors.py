"""Человеческие тексты для сырых системных ошибок.

Ночной сбой с «[WinError 32] The process cannot access the file…» вызывает
панику у не-технаря. Словарь превращает типовые системные ошибки в понятное
«что случилось и что сделать»; нераспознанное получает нейтральную обёртку
со ссылкой на журнал приложения.
"""

from __future__ import annotations

_WINERROR_HINTS: dict[int, str] = {
    5: (
        "Нет доступа к файлу или папке. Проверьте, что папка не защищена от "
        "записи и не требует прав администратора."
    ),
    32: (
        "Файл занят другой программой — обычно это плеер или проводник с "
        "открытым предпросмотром. Закройте их и повторите."
    ),
    112: "На диске закончилось место. Освободите место и повторите.",
    1224: "Файл изменён другой программой во время работы. Повторите операцию.",
    1920: "Файл недоступен (облачная папка не синхронизирована?). Проверьте OneDrive/облако.",
}

_ERRNO_HINTS: dict[int, str] = {
    13: (  # EACCES
        "Нет доступа к файлу или папке. Проверьте, что папка не только для чтения."
    ),
    28: "На диске закончилось место. Освободите место и повторите.",  # ENOSPC
}


def humanize_error(exc: BaseException) -> str:
    """Понятный русский текст ошибки; для наших доменных ошибок — как есть.

    Доменные ошибки проекта (JobError, DiskSpaceError, ProbeError, …) уже
    человекочитаемы — их текст не трогаем. Системные OSError получают
    подсказку, остальное — нейтральную обёртку.
    """
    text = str(exc) or exc.__class__.__name__
    # свои сообщения по-русски пропускаем без изменений
    if any("а" <= ch.lower() <= "я" or ch.lower() == "ё" for ch in text):
        return text
    if isinstance(exc, OSError):
        winerror = getattr(exc, "winerror", None)
        if winerror in _WINERROR_HINTS:
            return f"{_WINERROR_HINTS[winerror]}\n(Техническая деталь: {text})"
        if exc.errno in _ERRNO_HINTS:
            return f"{_ERRNO_HINTS[exc.errno]}\n(Техническая деталь: {text})"
        return (
            "Системная ошибка при работе с файлами. Подробности — в журнале "
            f"приложения (меню «Проект»).\n(Техническая деталь: {text})"
        )
    return (
        "Внутренняя ошибка. Подробности записаны в журнал приложения "
        f"(меню «Проект» → «Открыть журнал»).\n(Техническая деталь: {text})"
    )
